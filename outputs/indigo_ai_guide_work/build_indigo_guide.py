def set_run_font(run, size=None, bold=None):
    run.font.name = "맑은 고딕"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "맑은 고딕")
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold


def set_para_font(paragraph, size=10, bold=None):
    for run in paragraph.runs:
        set_run_font(run, size=size, bold=bold if bold is not None else run.bold)


def clear_body(doc):
    body = doc._body._element
    for child in list(body):
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)


def p(doc, text="", bold=False, size=10, before=None, after=None):
    para = doc.add_paragraph()
    if text:
        run = para.add_run(text)
        set_run_font(run, size=size, bold=bold)
    if before is not None:
        para.paragraph_format.space_before = Pt(before)
    if after is not None:
        para.paragraph_format.space_after = Pt(after)
    return para


def lines(doc, items, size=10):
    for item in items:
        p(doc, item, size=size)


def add_table(doc, rows, widths=None):
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = "Table Grid"
    for r_idx, row in enumerate(rows):
        cells = table.rows[r_idx].cells
        for c_idx, value in enumerate(row):
            cells[c_idx].text = ""
            para = cells[c_idx].paragraphs[0]
            run = para.add_run(value)
            set_run_font(run, size=9, bold=(r_idx == 0))
            if widths and c_idx < len(widths):
                cells[c_idx].width = widths[c_idx]
    p(doc)
    return table


def add_page_break(doc):
    para = doc.add_paragraph()
    para.add_run().add_break(WD_BREAK.PAGE)


